"""Bounded, GUI-independent contracts for deterministic agent planning."""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
import re
from typing import Any

from .agent_preflight import PreflightReadiness, PreflightResult
from .observation import DatasetMode, WavelengthAxisStatus


MAX_PLAN_STEPS = 5
MAX_EVIDENCE_REFERENCES = 16
MAX_EVIDENCE_REFERENCES_PER_STEP = 8
MAX_SUMMARY_ITEMS = 16
MAX_TEXT_LENGTH = 240
MAX_REFERENCE_LENGTH = 80
MAX_GRAPH_NODES = 4

_EVIDENCE_REFERENCE = re.compile(r"(?:image:frame:[0-9]{1,6}|spectrum:(?:full-source|plot))\Z")


class PlanningStatus(str, Enum):
    READY_PLAN = "ready_plan"
    NEEDS_INPUT = "needs_input"
    BLOCKED_INVALID_DATA = "blocked_invalid_data"
    STALE = "stale"
    CANCELLED = "cancelled"
    FAILED = "failed"
    UNAVAILABLE = "planning_unavailable"


class PlanStepType(str, Enum):
    INSPECT_DATASET_SUMMARY = "inspect_dataset_summary"
    REVIEW_IMAGE_PREVIEWS = "review_existing_image_previews"
    REVIEW_MEASURED_SPECTRUM = "review_existing_measured_spectrum"
    REQUEST_ROI = "request_explicit_roi_selection"
    REQUEST_CALIBRATION_REVIEW = "request_calibration_review"
    STOP_NEEDS_MORE_EVIDENCE = "stop_needs_more_evidence"


class FuturePermissionClass(str, Enum):
    """Classification only; M3 grants no permission to execute a proposal."""

    LOCAL_READ_ONLY = "local_read_only_proposal"
    HUMAN_INPUT_REQUIRED = "human_input_required"


class PlanningErrorCode(str, Enum):
    INVALID_PREFLIGHT = "invalid_preflight"
    INVALID_STATE = "invalid_state"
    PLAN_REJECTED = "plan_rejected"
    NO_EVIDENCE = "no_evidence"
    DEPENDENCY_MISSING = "optional_dependency_missing"
    CANCELLED = "cancelled"
    STALE = "stale"
    UNEXPECTED = "planning_failed"


@dataclass(frozen=True)
class PlanningContext:
    """Only bounded, JSON-compatible facts cross into the planning worker."""

    run_id: str
    preflight_run_id: str
    preflight_complete: bool
    dataset_id: str
    revision: int
    readiness: PreflightReadiness
    mode: DatasetMode
    wavelength_axis_status: WavelengthAxisStatus
    images_available: bool
    spectrum_available: bool
    mapping_applicable: bool
    roi_available: bool
    calibration_provenance_known: bool
    spectrum_has_nonfinite: bool
    evidence_references: tuple[str, ...]
    observations: tuple[str, ...]
    warnings: tuple[str, ...]


@dataclass(frozen=True)
class PlanStep:
    """A read-only proposal, never an executable scientific command."""

    step_type: PlanStepType
    rationale: str
    evidence_ids: tuple[str, ...]
    supported: bool
    requires_human_input: bool
    permission_classification: FuturePermissionClass


@dataclass(frozen=True)
class PlanningOutcome:
    run_id: str
    preflight_run_id: str
    dataset_id: str
    revision: int
    status: PlanningStatus
    steps: tuple[PlanStep, ...] = ()
    transitions: tuple[str, ...] = ()
    error_code: PlanningErrorCode | None = None
    message: str = ""


class PlanningValidationError(ValueError):
    """Raised when a preflight summary or proposed plan violates the contract."""


def _validate_text(value: object, field_name: str) -> str:
    if not isinstance(value, str) or not value or len(value) > MAX_TEXT_LENGTH:
        raise PlanningValidationError(f"{field_name} is not bounded text.")
    # These fields are generated by NEAT's deterministic preflight. Reject path,
    # URL, and credential-like data defensively before building graph state.
    lowered = value.lower()
    if (
        "://" in lowered
        or re.search(r"[a-z]:[/\\]", lowered)
        or value.startswith(("\\\\", "//", "/"))
        or re.search(r"(?:^|\s)/(?:[^/\s]+/)*[^/\s]+", value)
        or re.search(r"(?:^|\s)(?:\.{1,2}|~)[/\\]", value)
        or any(marker in lowered for marker in ("api_key", "token="))
    ):
        raise PlanningValidationError(f"{field_name} contains disallowed private data.")
    return value


def _validate_references(references: tuple[str, ...]) -> tuple[str, ...]:
    if len(references) > MAX_EVIDENCE_REFERENCES:
        raise PlanningValidationError("Too many evidence references.")
    if len(set(references)) != len(references):
        raise PlanningValidationError("Evidence references must be unique.")
    for reference in references:
        if (
            not isinstance(reference, str)
            or len(reference) > MAX_REFERENCE_LENGTH
            or _EVIDENCE_REFERENCE.fullmatch(reference) is None
        ):
            raise PlanningValidationError("An evidence reference is not allowlisted.")
    return references


def context_from_preflight(
    result: PreflightResult, *, run_id: str
) -> PlanningContext:
    """Copy safe facts from a current preflight, excluding arrays and previews."""
    if (
        not run_id
        or len(run_id) > MAX_REFERENCE_LENGTH
        or not result.run_id
        or not result.dataset_id
        or result.revision < 0
        or result.assessment.dataset_id != result.dataset_id
        or result.assessment.revision != result.revision
        or result.dataset.dataset_id != result.dataset_id
        or result.dataset.revision != result.revision
    ):
        raise PlanningValidationError("Preflight identity and revision do not agree.")

    refs = _validate_references(tuple(result.assessment.evidence_references))
    if len(result.assessment.observations) > MAX_SUMMARY_ITEMS:
        raise PlanningValidationError("Preflight observations exceed the state limit.")
    if len(result.assessment.warnings) > MAX_SUMMARY_ITEMS:
        raise PlanningValidationError("Preflight warnings exceed the state limit.")
    observations = tuple(
        _validate_text(item, "Preflight observation")
        for item in result.assessment.observations
    )
    warnings = tuple(
        _validate_text(item, "Preflight warning") for item in result.assessment.warnings
    )

    return PlanningContext(
        run_id=run_id,
        preflight_run_id=result.run_id,
        preflight_complete=True,
        dataset_id=result.dataset_id,
        revision=result.revision,
        readiness=result.assessment.readiness,
        mode=result.dataset.mode,
        wavelength_axis_status=result.dataset.wavelength_axis_status,
        images_available=bool(result.dataset.capabilities.images_available),
        spectrum_available=bool(result.dataset.capabilities.spectrum_available),
        mapping_applicable=bool(result.dataset.capabilities.mapping_applicable),
        roi_available=result.roi is not None,
        calibration_provenance_known=(
            result.dataset.provenance.wavelength_source not in {"", "unknown"}
        ),
        spectrum_has_nonfinite=(
            result.spectrum is not None
            and result.spectrum.nonfinite_intensity_count > 0
        ),
        evidence_references=refs,
        observations=observations,
        warnings=warnings,
    )


def context_to_state(context: PlanningContext) -> dict[str, Any]:
    """Return an explicitly allowlisted, JSON-compatible LangGraph state."""
    for identity in (context.run_id, context.preflight_run_id, context.dataset_id):
        if (
            not isinstance(identity, str)
            or not identity
            or len(identity) > MAX_REFERENCE_LENGTH
            or re.fullmatch(r"[A-Za-z0-9_-]+", identity) is None
        ):
            raise PlanningValidationError("Planning identity is malformed.")
    if not isinstance(context.revision, int) or isinstance(context.revision, bool) or context.revision < 0:
        raise PlanningValidationError("Planning revision must be a non-negative integer.")
    if not isinstance(context.preflight_complete, bool):
        raise PlanningValidationError("Preflight completion state must be boolean.")
    if not isinstance(context.readiness, PreflightReadiness):
        raise PlanningValidationError("Preflight readiness is invalid.")
    if not isinstance(context.mode, DatasetMode) or not isinstance(
        context.wavelength_axis_status, WavelengthAxisStatus
    ):
        raise PlanningValidationError("Dataset mode or wavelength status is invalid.")
    refs = _validate_references(context.evidence_references)
    return {
        "run_id": context.run_id,
        "preflight_run_id": context.preflight_run_id,
        "preflight_complete": context.preflight_complete,
        "dataset_id": context.dataset_id,
        "revision": context.revision,
        "readiness": context.readiness.value,
        "mode": context.mode.value,
        "wavelength_axis_status": context.wavelength_axis_status.value,
        "capabilities": {
            "images_available": context.images_available,
            "spectrum_available": context.spectrum_available,
            "mapping_applicable": context.mapping_applicable,
        },
        "roi_available": context.roi_available,
        "calibration_provenance_known": context.calibration_provenance_known,
        "spectrum_has_nonfinite": context.spectrum_has_nonfinite,
        "evidence_references": list(refs),
        "observations": [
            _validate_text(item, "Preflight observation") for item in context.observations
        ],
        "warnings": [
            _validate_text(item, "Preflight warning") for item in context.warnings
        ],
        "steps": [],
        "route": "",
        "error_code": "",
        "transitions": [],
    }


